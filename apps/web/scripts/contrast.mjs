// Computes the WCAG contrast ratio of every text/background pair the design system uses, from the values in packages/ui-tokens/tokens.css, and writes
// docs/web-redesign/contrast.md. Readable text must reach 4.5:1; disabled controls are exempt. Exits 1 if any readable pair fails.
// Usage: node scripts/contrast.mjs [--check]   (--check prints instead of writing)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, "../../../packages/ui-tokens/tokens.css"), "utf8");
const tok = (name) => {
  const m = css.match(new RegExp(`--color-${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`token --color-${name} not found`);
  return m[1].trim();
};
const parse = (v) => {
  const hex = v.match(/^#([0-9a-f]{6})$/i);
  if (hex) return { r: parseInt(hex[1].slice(0, 2), 16), g: parseInt(hex[1].slice(2, 4), 16), b: parseInt(hex[1].slice(4, 6), 16), a: 1 };
  const rgb = v.match(/^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*(?:\/\s*([\d.]+))?\s*\)/);
  if (rgb) return { r: +rgb[1], g: +rgb[2], b: +rgb[3], a: rgb[4] === undefined ? 1 : +rgb[4] };
  throw new Error(`cannot parse ${v}`);
};
const over = (fg, bg) => ({ r: fg.r * fg.a + bg.r * (1 - fg.a), g: fg.g * fg.a + bg.g * (1 - fg.a), b: fg.b * fg.a + bg.b * (1 - fg.a), a: 1 });
const lin = (c) => { const s = c / 255; return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; };
const lum = ({ r, g, b }) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const hex = ({ r, g, b }) => "#" + [r, g, b].map((n) => Math.round(n).toString(16).padStart(2, "0")).join("");

const page = parse(tok("page"));
const surface = {
  page, tile: parse(tok("tile")),
  /* the banner grain: black noise at most 0.35 x 0.5 = 17.5% opaque over the band */
  "data-grain": over({ r: 0, g: 0, b: 0, a: 0.175 }, parse(tok("data"))), card: over(parse(tok("card")), page), data: parse(tok("data")), "ink-10": over(parse(tok("ink-10")), page), button: parse(tok("button")), "ink-soft": parse(tok("ink-soft")),
};
const text = { ink: parse(tok("ink")), muted: parse(tok("muted")), "on-button": parse(tok("on-button")), danger: parse(tok("danger")), disabled: parse(tok("disabled")) };

const pairs = [
  ["ink", "page", "Body text"], ["ink", "tile", "Text on a list tile or chip"], ["ink", "card", "Text on a card"], ["ink", "data", "Banner headline"], ["ink", "data-grain", "Banner headline over the darkest grain"], ["ink", "ink-10", "Text on a secondary button"],
  ["muted", "page", "Muted text on the page"], ["muted", "tile", "Muted text on a tile"], ["muted", "card", "Muted text on a card"], ["muted", "data", "Muted text on the banner band"],
  ["on-button", "button", "Primary button label"], ["on-button", "ink-soft", "Primary button label, hover"],
  ["danger", "page", "Failure text on the page"], ["danger", "tile", "Failure text on a tile"], ["danger", "card", "Failure text on a card"],
  ["disabled", "page", "Disabled control label (exempt from the 4.5 rule)"],
];
const rows = pairs.map(([t, s, use]) => {
  const fg = text[t].a < 1 ? over(text[t], surface[s]) : text[t];
  const r = ratio(fg, surface[s]);
  const exempt = t === "disabled";
  return { t, s, use, fg: hex(fg), bg: hex(surface[s]), r, pass: exempt || r >= 4.5, exempt };
});
const md = [
  "# Contrast report",
  "",
  "Generated by `apps/web/scripts/contrast.mjs` from `packages/ui-tokens/tokens.css`. WCAG 2.x relative luminance. Readable text needs 4.5:1; disabled controls are exempt. The palette is greyscale plus one failure colour (the owner declined the proposed green).",
  "",
  "| Text | Background | Use | Text colour | Background colour | Ratio | Result |",
  "|---|---|---|---|---|---|---|",
  ...rows.map((x) => `| ${x.t} | ${x.s} | ${x.use} | ${x.fg} | ${x.bg} | ${x.r.toFixed(2)}:1 | ${x.exempt ? "exempt" : x.pass ? "pass" : "FAIL"} |`),
  "",
  "The banner carries one line of ink text only; muted text is never placed on the grain (it would fall to about 3.3:1).",
  "",
  "Hairlines (ink at 20%) are decoration, not text. Interactive boundaries that carry meaning on their own (the 2px focus ring) are solid ink on white (21:1).",
  "",
].join("\n");
if (process.argv.includes("--check")) console.log(md);
else writeFileSync(join(here, "../../../docs/web-redesign/contrast.md"), md);
const failed = rows.filter((x) => !x.pass);
console.log(failed.length ? `FAIL: ${failed.map((x) => `${x.t} on ${x.s} ${x.r.toFixed(2)}`).join(", ")}` : `all ${rows.length} pairs pass (${rows.filter((x) => x.exempt).length} exempt)`);
process.exit(failed.length ? 1 : 0);
