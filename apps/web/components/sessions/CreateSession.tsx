"use client";

import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { useForm } from "react-hook-form";
import { can } from "../../lib/permissions/can.ts";
import { sessionForm, zodResolver, type SessionForm } from "../../lib/schemas.ts";
import { client } from "../../lib/tobin/index.ts";
import type { CreatedSession } from "../../lib/tobin/types.ts";
import { PageFrame } from "../shell/PageFrame.tsx";
import { useWorkspace } from "../shell/session.tsx";
import { Button, ButtonLink } from "../ui/Button.tsx";
import { AccessDenied, ErrorState, InlineError, NotSupported, Skeleton } from "../ui/Feedback.tsx";
import { TextField } from "../ui/Form.tsx";
import { StatGrid } from "../ui/Surfaces.tsx";
import { CopyButton, reasonOf } from "./shared.tsx";

type Step = "details" | "participants" | "review" | "created";
const STEPS: { key: Exclude<Step, "created">; label: string }[] = [
  { key: "details", label: "Details" },
  { key: "participants", label: "Participants" },
  { key: "review", label: "Review" },
];

interface Outcome { session: CreatedSession; added: string[]; failed: { name: string; reason: string }[] }

export function CreateSession() {
  const { org, actor } = useWorkspace();
  const qc = useQueryClient();
  const allowed = can(actor, "sessions.create");
  const [step, setStep] = useState<Step>("details");
  const [label, setLabel] = useState("");
  const [picked, setPicked] = useState<Set<string>>(new Set());
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [outcome, setOutcome] = useState<Outcome | null>(null);
  const members = useQuery({ queryKey: ["members", org.id], queryFn: () => client.organizations.members(org.id), enabled: allowed.allowed });
  const form = useForm<SessionForm>({ resolver: zodResolver(sessionForm), defaultValues: { label: "" } });

  if (!allowed.allowed) {
    return (
      <PageFrame title="Create session" breadcrumbs={[{ label: org.name }, { href: "/sessions", label: "Clearing Sessions" }, { label: "Create" }]}>
        <AccessDenied title="You cannot create sessions" message={<>{allowed.reason} Ask an administrator of {org.name} to create the session, or to make you an administrator.</>} />
      </PageFrame>
    );
  }

  const active = (members.data ?? []).filter((m) => m.status === "active");
  const chosen = active.filter((m) => picked.has(m.userId));

  const create = async () => {
    setBusy(true); setError(null);
    try {
      const session = await client.sessions.create(org.id, label);
      const added: string[] = []; const failed: Outcome["failed"] = [];
      for (const m of chosen) {
        try { await client.participants.add(org.id, session.sessionId, m.userId); added.push(m.name); } catch (e) { failed.push({ name: m.name, reason: reasonOf(e) }); }
      }
      await qc.invalidateQueries({ queryKey: ["sessions", org.id] });
      setOutcome({ session, added, failed });
      setStep("created");
    } catch (e) {
      setError(reasonOf(e));
    } finally { setBusy(false); }
  };

  return (
    <PageFrame title="Create session" breadcrumbs={[{ label: org.name }, { href: "/sessions", label: "Clearing Sessions" }, { label: "Create" }]} sensitive>
      <div className="mx-auto w-full max-w-[640px] rounded-panel bg-panel p-6 sm:p-8">
        {step !== "created" ? (
          <ol className="mb-6 flex gap-5" aria-label="Steps">
            {STEPS.map((s, i) => (
              <li key={s.key} aria-current={s.key === step ? "step" : undefined} className={s.key === step ? "text-body font-medium text-ink" : "text-body text-muted"}>
                {i + 1}. {s.label}
              </li>
            ))}
          </ol>
        ) : null}

        {step === "details" ? (
          <form className="space-y-4" noValidate onSubmit={form.handleSubmit((v) => { setLabel(v.label); setStep("participants"); })}>
            <h2 className="text-title font-medium">Name the session</h2>
            <p className="text-body text-muted">The name is the only detail the backend records. The session id is generated by the server.</p>
            <TextField id="session-label" label="Session name" maxLength={80} autoComplete="off" error={form.formState.errors.label?.message} {...form.register("label")} />
            <div className="space-y-2">
              <NotSupported tone="card" feature="Assets, deadlines, settlement parameters and invitations" reason="A session has no fields for these. Assets are set on each obligation; deadlines and invitations to other organizations do not exist." />
            </div>
            <div className="flex flex-col-reverse gap-2 sm:flex-row">
              <ButtonLink href="/sessions" variant="quiet">Cancel</ButtonLink>
              <Button type="submit" variant="primary" className="sm:flex-1">Continue</Button>
            </div>
          </form>
        ) : null}

        {step === "participants" ? (
          <div className="space-y-4">
            <h2 className="text-title font-medium">Add participants</h2>
            <p className="text-body text-muted">Participants are members of {org.name}. You can also add or remove them later while the session is being configured. Adding a participant records it in Tobin only: it is not an on-chain admission.</p>
            {members.isLoading ? <Skeleton lines={3} /> : members.error ? <ErrorState title="Could not load members" message={reasonOf(members.error)} retry={<Button onClick={() => members.refetch()}>Try again</Button>} /> : (
              <fieldset className="rounded-card bg-card p-2">
                <legend className="sr-only">Members of {org.name}</legend>
                {active.length === 0 ? <p className="p-3 text-body text-muted">No active members.</p> : (
                  <ul className="divide-y divide-divider">
                    {active.map((m) => (
                      <li key={m.userId}>
                        <label className="flex min-h-12 cursor-pointer items-center gap-3 px-3 py-2">
                          <input type="checkbox" className="size-4 accent-[var(--color-button)]" checked={picked.has(m.userId)}
                            onChange={(e) => setPicked((p) => { const n = new Set(p); if (e.target.checked) n.add(m.userId); else n.delete(m.userId); return n; })} />
                          <span className="min-w-0 flex-1"><span className="block truncate text-body font-medium">{m.name}{m.you ? " (you)" : ""}</span><span className="block text-label text-muted">{m.role === "admin" ? "Admin" : "Member"}{m.reviewer ? ", Reviewer" : ""}</span></span>
                        </label>
                      </li>
                    ))}
                  </ul>
                )}
              </fieldset>
            )}
            <NotSupported tone="card" feature="Participants from other organizations" reason="Every participant is a member of this organization. Cross-organization sessions and joining do not exist in the backend." />
            <div className="flex flex-col-reverse gap-2 sm:flex-row">
              <Button variant="quiet" onClick={() => setStep("details")}>Back</Button>
              <Button variant="primary" className="sm:flex-1" onClick={() => setStep("review")}>Review</Button>
            </div>
          </div>
        ) : null}

        {step === "review" ? (
          <div className="space-y-4">
            <h2 className="text-title font-medium">Review</h2>
            <div className="rounded-card bg-card p-4">
              <StatGrid columns={2} items={[
                { label: "Session name", value: label },
                { label: "Organization", value: org.name },
                { label: "Record", value: "Local draft" },
                { label: "Participants", value: chosen.length === 0 ? "None yet" : chosen.map((m) => m.name).join(", ") },
              ]} />
            </div>
            <p className="rounded-card bg-card p-3 text-body text-muted">This creates a local draft in Tobin. No contract is called, no wallet is used and nothing is sent to Stellar, so it is not an on-chain session. Obligations, calculation and review come after.</p>
            {error ? <InlineError>{error}</InlineError> : null}
            <div className="flex flex-col-reverse gap-2 sm:flex-row">
              <Button variant="quiet" onClick={() => setStep("participants")} disabled={busy}>Back</Button>
              <Button variant="primary" className="sm:flex-1" loading={busy} onClick={create}>Create session</Button>
            </div>
          </div>
        ) : null}

        {step === "created" && outcome ? (
          <div className="space-y-4" role="status">
            <h2 className="text-title font-medium">Session created</h2>
            <p className="text-body text-muted">&ldquo;{outcome.session.label}&rdquo; is recorded as a local draft. It is not an on-chain session.</p>
            <div className="rounded-card bg-card p-4">
              <p className="text-label uppercase tracking-wide text-muted">Session id</p>
              <p className="mt-1 break-all font-mono text-ident" data-testid="created-session-id">{outcome.session.sessionId}</p>
              <div className="mt-3"><CopyButton value={outcome.session.sessionId} label="Copy session id" /></div>
            </div>
            {outcome.added.length > 0 ? <p className="text-body text-muted">Added: {outcome.added.join(", ")}.</p> : null}
            {outcome.failed.length > 0 ? (
              <div className="rounded-card bg-card p-3" role="alert">
                <p className="text-body font-medium text-danger">{outcome.failed.length} participant{outcome.failed.length === 1 ? " was" : "s were"} not added</p>
                <ul className="mt-1 text-body">{outcome.failed.map((f) => <li key={f.name}>{f.name}: {f.reason}</li>)}</ul>
                <p className="mt-1 text-label text-muted">The session exists. Add them on its Participants tab.</p>
              </div>
            ) : null}
            <div className="flex flex-col gap-2 sm:flex-row">
              <ButtonLink href="/sessions" variant="quiet">Back to sessions</ButtonLink>
              <ButtonLink href={`/sessions/${outcome.session.sessionId}`} variant="primary" className="sm:flex-1">Open session workspace</ButtonLink>
            </div>
          </div>
        ) : null}
      </div>
    </PageFrame>
  );
}
