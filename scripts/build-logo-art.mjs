// Regenerates src/components/logo-art.ts from brand-pack/svg.
// Inline copies drop the <metadata> (C2PA provenance) blob, which is ~90% of each
// file and useless in the DOM, and swap the fixed gradient ids for placeholders
// that <Logo> replaces with useId()-based ones.
//
// The brand pack's lockups carry an outlined wordmark. On the site the wordmark is
// live JetBrains Mono text instead: the outlined glyph group is swapped for a <text>
// element that picks up the page's --font-mono, and the viewBox is widened to fit
// the monospaced letters. The files in brand-pack/ are left untouched.
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => readFileSync(new URL(`../brand-pack/svg/${f}.svg`, import.meta.url), "utf8");

// Lockup geometry (user units). The symbol keeps its original placement; the text
// starts where the outlined wordmark started.
const LOCKUP_W = 300;
const TEXT = { x: 124, y: 80, size: 54, spacing: -2 };

function wordmark(fill) {
  return (
    `<text x="${TEXT.x}" y="${TEXT.y}" fill="${fill}" font-size="${TEXT.size}" font-weight="800" ` +
    `letter-spacing="${TEXT.spacing}" style="font-family:var(--font-mono),ui-monospace,monospace">TOBIN</text>`
  );
}

function parse(file, { flatToCurrentColor = false, lockup = false } = {}) {
  let s = read(file).replace(/<metadata>[\s\S]*?<\/metadata>/, "");
  const vb = s.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  let inner = s.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  inner = inner.replace(/id="iri"/g, 'id="__IRI__"').replace(/id="hl"/g, 'id="__HL__"');
  inner = inner.replace(/url\(#iri\)/g, "url(#__IRI__)").replace(/url\(#hl\)/g, "url(#__HL__)");
  if (flatToCurrentColor) inner = inner.replace(/stroke="#[0-9a-fA-F]{6}"/g, 'stroke="currentColor"');
  let w = +vb[1];
  if (lockup) {
    // The outlined wordmark is the last <g fill="..."> group in the file.
    const group = /<g fill="(#[0-9a-fA-F]{6})"><path transform="translate\(123[^"]*"[^>]*><\/path><\/g>\s*$/;
    const m = inner.match(group);
    if (!m) throw new Error(`${file}: wordmark group not found`);
    inner = inner.replace(group, wordmark(m[1]));
    w = LOCKUP_W;
  }
  return { w, h: +vb[2], inner };
}

const art = {
  symbolGlossy: parse("tobin-symbol-glossy"),
  symbolFlat: parse("tobin-symbol-flat-black", { flatToCurrentColor: true }),
  lockupLight: parse("tobin-logo-light", { lockup: true }),
  lockupDark: parse("tobin-logo-dark", { lockup: true }),
  lockupBlack: parse("tobin-logo-black", { lockup: true }),
  lockupWhite: parse("tobin-logo-white", { lockup: true }),
};

const out = `// GENERATED by scripts/build-logo-art.mjs from brand-pack/svg. Do not edit by hand.
export type Art = { w: number; h: number; inner: string };

export const ART = ${JSON.stringify(art, null, 2)} satisfies Record<string, Art>;
`;
writeFileSync(new URL("../src/components/logo-art.ts", import.meta.url), out);
console.log(Object.entries(art).map(([k, v]) => `${k}: ${v.w}x${v.h}, ${v.inner.length}B`).join("\n"));
