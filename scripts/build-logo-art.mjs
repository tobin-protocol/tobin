// Regenerates src/components/logo-art.ts from brand-pack/svg.
// Inline copies drop the <metadata> (C2PA provenance) blob, which is ~90% of each
// file and useless in the DOM, and swap the fixed gradient ids for placeholders
// that <Logo> replaces with useId()-based ones.
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => readFileSync(new URL(`../brand-pack/svg/${f}.svg`, import.meta.url), "utf8");

function parse(file, { flatToCurrentColor = false } = {}) {
  let s = read(file).replace(/<metadata>[\s\S]*?<\/metadata>/, "");
  const vb = s.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  let inner = s.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  inner = inner.replace(/id="iri"/g, 'id="__IRI__"').replace(/id="hl"/g, 'id="__HL__"');
  inner = inner.replace(/url\(#iri\)/g, "url(#__IRI__)").replace(/url\(#hl\)/g, "url(#__HL__)");
  if (flatToCurrentColor) inner = inner.replace(/stroke="#[0-9a-fA-F]{6}"/g, 'stroke="currentColor"');
  return { w: +vb[1], h: +vb[2], inner };
}

const art = {
  symbolGlossy: parse("tobin-symbol-glossy"),
  symbolFlat: parse("tobin-symbol-flat-black", { flatToCurrentColor: true }),
  lockupLight: parse("tobin-logo-light"),
  lockupDark: parse("tobin-logo-dark"),
  lockupBlack: parse("tobin-logo-black"),
  lockupWhite: parse("tobin-logo-white"),
};

const out = `// GENERATED by scripts/build-logo-art.mjs from brand-pack/svg. Do not edit by hand.
export type Art = { w: number; h: number; inner: string };

export const ART = ${JSON.stringify(art, null, 2)} satisfies Record<string, Art>;
`;
writeFileSync(new URL("../src/components/logo-art.ts", import.meta.url), out);
console.log(Object.entries(art).map(([k, v]) => `${k}: ${v.w}x${v.h}, ${v.inner.length}B`).join("\n"));
